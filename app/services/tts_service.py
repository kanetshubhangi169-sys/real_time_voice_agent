from sarvamai import SarvamAI

from app.config import settings


class TTSService:
    """
    Text-to-speech service using Sarvam AI Bulbul v3.

    Supports Indian languages and English.
    """

    def __init__(self):

        if not settings.sarvam_api_key:
            raise ValueError(
                "SARVAM_API_KEY is not configured."
            )

        self.client = SarvamAI(
            api_subscription_key=settings.sarvam_api_key
        )

        self.model_id = settings.tts_model_id
        self.speaker = settings.tts_speaker
        self.sample_rate = settings.tts_sample_rate
        self.codec = settings.tts_codec

    def synthesize(
        self,
        text: str,
        language: str = "en"
    ) -> bytes:
        """
        Convert text into speech using Sarvam Bulbul v3.

        Args:
            text:
                Text generated by the LLM.

            language:
                Language detected by STT.

        Returns:
            Generated audio bytes.
        """

        if not text or not text.strip():
            raise ValueError(
                "Text cannot be empty."
            )

        language_code = self._get_language_code(
            language
        )

        try:

            response = (
                self.client.text_to_speech.convert(
                    text=text.strip(),
                    model=self.model_id,
                    language_code=language_code,
                    speaker=self.speaker,
                    speech_sample_rate=self.sample_rate,
                    output_audio_codec=self.codec,
                )
            )

            if not response.audios:
                raise RuntimeError(
                    "Sarvam TTS returned no audio."
                )

            audio = response.audios[0]

            # Sarvam SDK may return either
            # bytes or a base64 encoded string.

            if isinstance(audio, bytes):
                return audio

            import base64

            audio_bytes = base64.b64decode(
                audio
            )

            if not audio_bytes:
                raise RuntimeError(
                    "Sarvam TTS returned empty audio."
                )

            return audio_bytes

        except Exception as exc:

            raise RuntimeError(
                f"Sarvam text-to-speech failed: {exc}"
            ) from exc

    @staticmethod
    def _get_language_code(
        language: str | None
    ) -> str:
        """
        Convert detected language into
        Sarvam BCP-47 language code.
        """

        if not language:
            return "en-IN"

        language = str(
            language
        ).strip().lower()

        language_codes = {

            # --------------------------------------------------
            # English
            # --------------------------------------------------

            "en": "en-IN",
            "english": "en-IN",

            # --------------------------------------------------
            # Indian languages
            # --------------------------------------------------

            "hi": "hi-IN",
            "hindi": "hi-IN",

            "gu": "gu-IN",
            "gujarati": "gu-IN",

            "mr": "mr-IN",
            "marathi": "mr-IN",

            "bn": "bn-IN",
            "bengali": "bn-IN",

            "ta": "ta-IN",
            "tamil": "ta-IN",

            "te": "te-IN",
            "telugu": "te-IN",

            "kn": "kn-IN",
            "kannada": "kn-IN",

            "ml": "ml-IN",
            "malayalam": "ml-IN",

            "pa": "pa-IN",
            "punjabi": "pa-IN",

            "od": "od-IN",
            "or": "od-IN",
            "odia": "od-IN",

            "as": "as-IN",
            "assamese": "as-IN",

            "ur": "ur-IN",
            "urdu": "ur-IN",

            "sa": "sa-IN",
            "sanskrit": "sa-IN",

            "ne": "ne-IN",
            "nepali": "ne-IN",

            "sd": "sd-IN",
            "sindhi": "sd-IN",

        }

        return language_codes.get(
            language,
            "en-IN"
        )